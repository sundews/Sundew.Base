namespace Sundew.Base.Notifications.Generator;

using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

/// <summary>
/// Implements <see cref="INotificationOwner"/> for partial classes.
/// </summary>
/// <remarks>
/// A partial class that lists <see cref="INotificationOwner"/> gets <see cref="INotificationOwner.TargetSubscriptions"/> generated unless it
/// or a base class provides the property, and gets SubscribeTo methods generated unless it or a base class has a member of that name. The
/// methods subscribe the class to an event source with the class as the owner, so that code inside the class subscribes without passing
/// itself. They are protected, so that derived classes subscribe the same way, and private in a sealed class, where protected would warn.
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class NotificationOwnerGenerator : IIncrementalGenerator
{
    private const string PropertyName = nameof(INotificationOwner.TargetSubscriptions);
    private const string SubscribeToName = "SubscribeTo";
    private const string ProtectedModifier = "protected";
    private const string PrivateModifier = "private";
    private const string EventTypeParameterName = "TEvent";
    private const string SubscribedEventTypeParameterName = "TSubscribedEvent";
    private const string NewLine = "\r\n";
    private const string Indentation = "    ";
    private const string GlobalPrefix = "global::";
    private const string Dot = ".";
    private const string GeneratedFileExtension = ".g.cs";
    private const string Header = "// <auto-generated/>" + NewLine + "#nullable enable" + NewLine;
    private const string NamespaceKeyword = "namespace ";
    private const string PartialKeyword = "partial ";
    private const string RecordKeyword = "record ";
    private const string ClassKeyword = "class ";
    private const string TypeParametersStart = "<";
    private const string TypeParametersEnd = ">";
    private const string TypeParameterSeparator = ", ";
    private const string StatementEnd = ";" + NewLine;
    private const string OpenBrace = "{" + NewLine;
    private const string CloseBrace = "}" + NewLine;
    private const string PrivateReadonly = "private readonly ";
    private const string NewAssignment = " = new ";
    private const string ConstructionEnd = "();" + NewLine + NewLine;
    private const string InheritDoc = "/// <inheritdoc/>" + NewLine;
    private const string ExpressionBodyThis = " => this.";
    private const string SubscriptionTypeName = "Subscription";
    private const string NotifyTypeName = "INotify";
    private const string NotifyAnyTypeName = "INotifyAny";
    private const string CancellationTokenTypeName = GlobalPrefix + "System.Threading.CancellationToken";
    private const string ValueTaskTypeName = GlobalPrefix + "System.Threading.Tasks.ValueTask";
    private const string FuncTypeName = GlobalPrefix + "System.Func";
    private const string HandlerName = "handler";
    private const char Space = ' ';
    private static readonly string InterfaceMetadataName = typeof(INotificationOwner).FullName!;
    private static readonly string InterfaceTypeName = GlobalPrefix + InterfaceMetadataName;
    private static readonly string NotificationsNamespace = GlobalPrefix + typeof(INotificationOwner).Namespace + Dot;
    private static readonly string SubscriptionsTypeName = GlobalPrefix + typeof(Subscriptions).FullName;
    private static readonly string FieldName = char.ToLowerInvariant(PropertyName[0]) + PropertyName.Substring(1);

    /// <summary>
    /// The handler shapes that get a SubscribeTo overload: the handler parameters, with {0} for the event type and {1} for the subscription type,
    /// and the lambda that adapts such a handler to the full shape, or null for the full shape itself.
    /// </summary>
    private static readonly (string Parameters, string? Adapter)[] HandlerShapes =
    [
        ("{0}, {1}, " + CancellationTokenTypeName, null),
        ("{0}, " + CancellationTokenTypeName, "(@event, _, cancellationToken) => " + HandlerName + "(@event, cancellationToken)"),
        ("{0}, {1}", "(@event, subscription, _) => " + HandlerName + "(@event, subscription)"),
        ("{0}", "(@event, _, _) => " + HandlerName + "(@event)"),
    ];

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax or RecordDeclarationSyntax,
                static (syntaxContext, cancellationToken) => Analyze(syntaxContext, cancellationToken))
            .Where(static x => x is not null);

        context.RegisterSourceOutput(candidates, static (productionContext, result) => Emit(productionContext, result!));
    }

    private static CandidateResult? Analyze(GeneratorSyntaxContext syntaxContext, CancellationToken cancellationToken)
    {
        var declaration = (TypeDeclarationSyntax)syntaxContext.Node;
        if (syntaxContext.SemanticModel.GetDeclaredSymbol(declaration, cancellationToken) is not INamedTypeSymbol { TypeKind: TypeKind.Class } typeSymbol)
        {
            return null;
        }

        // Only a type that lists the interface itself, directly or through a derived interface, can implement it explicitly.
        // A type that inherits it from a base class relies on the base class, whose implementation may itself be generated.
        var interfaceSymbol = syntaxContext.SemanticModel.Compilation.GetTypeByMetadataName(InterfaceMetadataName);
        if (interfaceSymbol is null || !ListsInterface(typeSymbol, interfaceSymbol))
        {
            return null;
        }

        var propertySymbol = interfaceSymbol.GetMembers(PropertyName).OfType<IPropertySymbol>().FirstOrDefault();
        if (propertySymbol is null)
        {
            return null;
        }

        // What a base class gets generated is not visible here, so a base class that would generate counts as providing both members.
        var generatingBases = BaseTypes(typeSymbol).Where(x => ListsInterface(x, interfaceSymbol) && Chain(x).All(IsPartial)).ToList();
        var generateTargetSubscriptions = typeSymbol.FindImplementationForInterfaceMember(propertySymbol) is null && generatingBases.Count == 0;
        var generateSubscribeTo = typeSymbol.GetMembers(SubscribeToName).Length == 0
            && !BaseTypes(typeSymbol).Any(x => x.GetMembers(SubscribeToName).Any(member => member.DeclaredAccessibility != Accessibility.Private))
            && !generatingBases.Any(x => x.GetMembers(SubscribeToName).Length == 0);
        if (!generateTargetSubscriptions && !generateSubscribeTo)
        {
            return null;
        }

        // Only the first declaration generates, so a class split over several partial files generates once.
        var firstDeclaration = typeSymbol.DeclaringSyntaxReferences[0];
        if (firstDeclaration.SyntaxTree != declaration.SyntaxTree || firstDeclaration.Span != declaration.Span)
        {
            return null;
        }

        var chain = Chain(typeSymbol);
        if (!chain.All(IsPartial))
        {
            // The SubscribeTo methods are a convenience, so a class that only misses those is left alone.
            return generateTargetSubscriptions
                ? new CandidateResult(null, Diagnostic.Create(Diagnostics.NotPartial, declaration.Identifier.GetLocation(), typeSymbol.ToDisplayString()))
                : null;
        }

        var typeParameterNames = new HashSet<string>(chain.SelectMany(x => x.TypeParameters).Select(x => x.Name));
        var declarations = string.Join(NewLine, chain.Select(x => PartialKeyword + (x.IsRecord ? RecordKeyword : ClassKeyword) + x.Name + TypeParameters(x)));
        var @namespace = typeSymbol.ContainingNamespace.IsGlobalNamespace ? string.Empty : typeSymbol.ContainingNamespace.ToDisplayString();
        var hintName = (@namespace.Length == 0 ? string.Empty : @namespace + Dot) + string.Join(Dot, chain.Select(x => x.MetadataName)) + Dot + nameof(INotificationOwner) + GeneratedFileExtension;
        return new CandidateResult(
            new NotificationOwnerModel(
                hintName,
                @namespace,
                declarations,
                generateTargetSubscriptions,
                generateSubscribeTo ? (typeSymbol.IsSealed ? PrivateModifier : ProtectedModifier) : null,
                Unique(EventTypeParameterName, typeParameterNames),
                Unique(SubscribedEventTypeParameterName, typeParameterNames)),
            null);
    }

    private static bool ListsInterface(INamedTypeSymbol typeSymbol, INamedTypeSymbol interfaceSymbol)
    {
        return typeSymbol.Interfaces.Any(x => SymbolEqualityComparer.Default.Equals(x, interfaceSymbol) || x.AllInterfaces.Contains(interfaceSymbol, SymbolEqualityComparer.Default));
    }

    private static IEnumerable<INamedTypeSymbol> BaseTypes(INamedTypeSymbol typeSymbol)
    {
        for (var baseType = typeSymbol.BaseType; baseType is not null; baseType = baseType.BaseType)
        {
            yield return baseType;
        }
    }

    /// <summary>
    /// Gets the type and its containing types, outermost first.
    /// </summary>
    private static List<INamedTypeSymbol> Chain(INamedTypeSymbol typeSymbol)
    {
        var chain = new List<INamedTypeSymbol>();
        for (var current = typeSymbol; current is not null; current = current.ContainingType)
        {
            chain.Insert(0, current);
        }

        return chain;
    }

    private static bool IsPartial(INamedTypeSymbol typeSymbol)
    {
        return typeSymbol.DeclaringSyntaxReferences
            .Select(x => x.GetSyntax())
            .OfType<TypeDeclarationSyntax>()
            .Any(x => x.Modifiers.Any(SyntaxKind.PartialKeyword));
    }

    private static string TypeParameters(INamedTypeSymbol typeSymbol)
    {
        return typeSymbol.TypeParameters.Length == 0
            ? string.Empty
            : TypeParametersStart + string.Join(TypeParameterSeparator, typeSymbol.TypeParameters.Select(x => x.Name)) + TypeParametersEnd;
    }

    private static string Unique(string name, HashSet<string> taken)
    {
        var candidate = name;
        for (var i = 1; taken.Contains(candidate); i++)
        {
            candidate = name + i;
        }

        return candidate;
    }

    private static void Emit(SourceProductionContext productionContext, CandidateResult result)
    {
        if (result.Diagnostic is not null)
        {
            productionContext.ReportDiagnostic(result.Diagnostic);
            return;
        }

        var model = result.Model!;
        var declarations = model.Declarations.Split([NewLine], System.StringSplitOptions.None);
        var builder = new StringBuilder();
        builder.Append(Header);
        if (model.Namespace.Length != 0)
        {
            builder.Append(NamespaceKeyword).Append(model.Namespace).Append(StatementEnd);
        }

        builder.Append(NewLine);
        var indent = string.Empty;
        foreach (var declaration in declarations)
        {
            builder.Append(indent).Append(declaration).Append(NewLine).Append(indent).Append(OpenBrace);
            indent += Indentation;
        }

        if (model.GenerateTargetSubscriptions)
        {
            builder.Append(indent).Append(PrivateReadonly).Append(SubscriptionsTypeName).Append(Space).Append(FieldName).Append(NewAssignment).Append(SubscriptionsTypeName).Append(ConstructionEnd);
            builder.Append(indent).Append(InheritDoc);
            builder.Append(indent).Append(SubscriptionsTypeName).Append(Space).Append(InterfaceTypeName).Append(Dot).Append(PropertyName).Append(ExpressionBodyThis).Append(FieldName).Append(StatementEnd);
        }

        if (model.SubscribeToModifier is not null)
        {
            AppendSubscribeTo(builder, indent, model, model.GenerateTargetSubscriptions);
        }

        for (var i = declarations.Length - 1; i >= 0; i--)
        {
            indent = indent.Substring(Indentation.Length);
            builder.Append(indent).Append(CloseBrace);
        }

        productionContext.AddSource(model.HintName, SourceText.From(builder.ToString(), Encoding.UTF8));
    }

    private static void AppendSubscribeTo(StringBuilder builder, string indent, NotificationOwnerModel model, bool separate)
    {
        var subscriptionType = NotificationsNamespace + SubscriptionTypeName;
        var tEvent = model.EventTypeParameter;
        var tSubscribedEvent = model.SubscribedEventTypeParameter;
        foreach (var (parameters, adapter) in HandlerShapes)
        {
            var handlerType = FuncTypeName + TypeParametersStart + string.Format(parameters, tEvent, subscriptionType) + TypeParameterSeparator + ValueTaskTypeName + TypeParametersEnd;
            var member =
                $$"""
                /// <summary>
                /// Subscribes this notification owner to the specified event source.
                /// </summary>
                /// <typeparam name="{{tEvent}}">The type of event.</typeparam>
                /// <param name="notify">The event source.</param>
                /// <param name="{{HandlerName}}">The handler.</param>
                /// <returns>A subscription, owned by this notification owner.</returns>
                {{model.SubscribeToModifier}} {{subscriptionType}} {{SubscribeToName}}<{{tEvent}}>({{NotificationsNamespace}}{{NotifyTypeName}}<{{tEvent}}> notify, {{handlerType}} {{HandlerName}})
                {
                    return notify.Subscribe({{adapter ?? HandlerName}}, this);
                }
                """;
            AppendMember(builder, indent, separate, member);
            separate = true;
        }

        foreach (var (parameters, adapter) in HandlerShapes)
        {
            var handlerType = FuncTypeName + TypeParametersStart + string.Format(parameters, tSubscribedEvent, subscriptionType) + TypeParameterSeparator + ValueTaskTypeName + TypeParametersEnd;
            var member =
                $$"""
                /// <summary>
                /// Subscribes this notification owner to events of the subscribed type from the specified event source.
                /// </summary>
                /// <typeparam name="{{tEvent}}">The type of event.</typeparam>
                /// <typeparam name="{{tSubscribedEvent}}">The subscribed event type.</typeparam>
                /// <param name="notifyAny">The event source.</param>
                /// <param name="{{HandlerName}}">The handler.</param>
                /// <returns>A subscription, owned by this notification owner.</returns>
                {{model.SubscribeToModifier}} {{subscriptionType}} {{SubscribeToName}}<{{tEvent}}, {{tSubscribedEvent}}>({{NotificationsNamespace}}{{NotifyAnyTypeName}}<{{tEvent}}> notifyAny, {{handlerType}} {{HandlerName}})
                    where {{tSubscribedEvent}} : {{tEvent}}
                {
                    return notifyAny.Subscribe<{{tSubscribedEvent}}>({{adapter ?? HandlerName}}, this);
                }
                """;
            AppendMember(builder, indent, true, member);
        }
    }

    private static void AppendMember(StringBuilder builder, string indent, bool separate, string member)
    {
        if (separate)
        {
            builder.Append(NewLine);
        }

        foreach (var line in member.Split('\n'))
        {
            builder.Append(indent).Append(line.TrimEnd('\r')).Append(NewLine);
        }
    }

    private sealed record CandidateResult(NotificationOwnerModel? Model, Diagnostic? Diagnostic);
}
